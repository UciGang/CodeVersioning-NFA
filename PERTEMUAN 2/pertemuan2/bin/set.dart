void main() {
  Set<String> buah = {"Apel", "Melon", "Nanas"};

  print("Buah pertama adalah ${buah.first}");
  print("Buah terakhir adalah ${buah.last}");
  print("apakah buah masih ada ${buah.isNotEmpty}");
  print("apakah buah sudah habis ${buah.isEmpty}");
  print("ada berapa jenis buah ${buah.length}");
}
